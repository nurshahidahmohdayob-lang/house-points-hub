// Bundles the Life Competencies lesson data into ../assets/lc-data.js (window.LC).
//   cd lc && npm install && node build.mjs
// LC_SRC can point at another checkout of the digital-literacy app.
import * as esbuild from "esbuild";
import os from "node:os";
import path from "node:path";
import fs from "node:fs";

const LC_SRC = process.env.LC_SRC || path.join(os.homedir(), "Codes/digital-literacy/src/lib");
if (!fs.existsSync(LC_SRC)) throw new Error(`Life Competencies source not found at ${LC_SRC}`);

import { execSync } from "node:child_process";
function lcCommit() {
  try { return execSync("git rev-parse --short HEAD", { cwd: LC_SRC }).toString().trim(); } catch { return ""; }
}

const lcAlias = {
  name: "lc-alias",
  setup(b) {
    b.onResolve({ filter: /^@lc\// }, (a) => b.resolve("./" + a.path.slice(4), { resolveDir: LC_SRC, kind: a.kind }));

    // lessons.ts pulls in Supabase for saving; the Lessons area only needs buildLesson, so stub it out.
    b.onResolve({ filter: /supabase\/client$/ }, () => ({ path: "supabase-stub", namespace: "stub" }));
    b.onLoad({ filter: /.*/, namespace: "stub" }, () => ({ contents: "export const createClient = () => null;", loader: "js" }));
  },
};

await esbuild.build({
  entryPoints: [path.join(import.meta.dirname, "entry.ts")],
  bundle: true,
  minify: true,
  format: "iife",
  globalName: "LC",
  target: "es2020",
  outfile: path.join(import.meta.dirname, "..", "assets", "lc-data.js"),
  plugins: [lcAlias],
  resolveExtensions: [".ts", ".tsx", ".js"],
  define: {
    "process.env.NEXT_PUBLIC_SUPABASE_URL": '""',
    "process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY": '""',
    "process.env.NODE_ENV": '"production"',
    // stamped at bundle time, so the Lessons tab can say when these lessons were made
    "process.env.LC_BUILT_AT": JSON.stringify(new Date().toISOString()),
    "process.env.LC_COMMIT": JSON.stringify(lcCommit()),
  },
  banner: { js: "/* Life Competencies lesson data - generated by lc/build.mjs from the digital-literacy app. */" },
  logLevel: "warning",
});
const out = path.join(import.meta.dirname, "..", "assets", "lc-data.js");
console.log("wrote", out, (fs.statSync(out).size / 1024).toFixed(0) + " KB");

// A small file of just the class lists, for the student join page (play.html) — no need to load all the lessons there.
globalThis.window = globalThis;
(0, eval)(fs.readFileSync(out, "utf8"));
const lists = (globalThis.LC.CLASS_LISTS || []).map((c) => ({ id: c.id, label: c.label, year: c.year, students: c.students }));
fs.writeFileSync(path.join(import.meta.dirname, "..", "assets", "class-lists.js"),
  `/* Class lists from the Life Competencies app (src/lib/students.ts) - generated by lc/build.mjs. */\nwindow.CLASS_LISTS = ${JSON.stringify(lists)};\n`);
console.log("wrote class-lists.js", lists.map((c) => `${c.id}:${c.students.length}`).join(" "));
